def post_process_solution_wrapper(label_tokenizer, candidates):
    def post_process_solution(prob, response, output):
        scoring = {}
        response = response.replace("*", "")
        for drug, item in extract_json_blocks(response).items():
            drug = match_drug_fuzz(drug, label_tokenizer.vocabulary.token2idx.keys())
            if drug not in candidates: continue
            if isinstance(item['predict'], list):
                item['predict'] = item['predict'][0]
            item = {"reason": item['reason'], "predict": int(item["predict"])}
            scoring[drug] = item

        assert len(scoring) == len(candidates), f"Different size between pred/in: {len(scoring)}-{len(candidates)}"
        return prob, (response, scoring), output

    return post_process_solution


