def candidate_similarity(candidate, context, similarity_dict):
    scores = []
    for other in context:
        keys = [f"{candidate}-{other}", f"{other}-{candidate}"]
        if keys[0] in similarity_dict:
            scores.append(similarity_dict[keys[0]])
        elif keys[1] in similarity_dict:
            scores.append(similarity_dict[keys[1]])
    return sum(scores)
