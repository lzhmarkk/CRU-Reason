def candidate2string(candidates, solution):
    context_node_ids = [graph.entity2id[x] for x in solution['conditions'] + solution['procedures']]

    candidate_string_dict = defaultdict(list)
    for node in candidates:
        triplets = get_neighbors(node, candidate_ids=context_node_ids, direction='both')
        triplets = [f"{src}->{rel.replace('_', ' ').lower()}->{dst}" for src, rel, dst in triplets]
        if len(triplets) >= 8: triplets = random.choices(triplets, k=8)
        candidate_string_dict[node].extend(triplets)

    return dict(candidate_string_dict)


def candidate2string_diag(candidates, solution):
    context_node_ids = [graph.entity2id[x] for x in solution['conditions'] + solution['procedures'] + solution['drugs']]

