def solution2string_with_overview(solution, overview, overview_only=True):
    solution_name = ""
    if not overview_only:
        if solution['conditions']:
            solution_name += "### Conditions\n" + "\n".join(solution['conditions']) + "\n"
        if solution['procedures']:
            solution_name += "### Procedures\n" + "\n".join(solution['procedures']) + "\n"
        solution_name += f"### Summary\n" + overview
    else:
        solution_name += overview
    return solution_name

